package report

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

// GenerateMarkdown renders STANDARDIZED_EVAL_REPORT.md.
//
// Structure contract:
//   - One section per benchmark. Within each section, the OFFICIAL BENCHMARK
//     METRIC block reports only what the official evaluator produced
//     (verbatim fields, counts within that benchmark). The SPLICE SUPPLEMENTAL
//     TELEMETRY block reports Splice-side counters for that same benchmark.
//   - The cross-benchmark view is a qualitative EVIDENCE MATRIX with cells
//     limited to "checks" | "cross" | "na". It never contains numbers.
//   - No overall score, no averaged tokens, no cross-benchmark number of any
//     kind appears anywhere in the document (enforced by the guard tests).
func GenerateMarkdown(records []*Record, reproductionCommands []string) (string, error) {
	if len(records) == 0 {
		return "", AggregationError{Msg: "GenerateMarkdown: no records"}
	}
	byBenchmark := map[string][]*Record{}
	for _, r := range records {
		if r == nil {
			return "", AggregationError{Msg: "GenerateMarkdown: nil record"}
		}
		byBenchmark[r.Benchmark] = append(byBenchmark[r.Benchmark], r)
	}
	benchmarks := make([]string, 0, len(byBenchmark))
	for b := range byBenchmark {
		benchmarks = append(benchmarks, b)
	}
	sort.Strings(benchmarks)

	var b strings.Builder
	b.WriteString("# STANDARDIZED EVAL REPORT\n\n")
	b.WriteString("Generated by benchmarks/report. Official metrics come from each\n")
	b.WriteString("benchmark's OFFICIAL evaluator, verbatim. Splice telemetry is\n")
	b.WriteString("supplemental and is never a benchmark metric.\n\n")

	b.WriteString("## Reproduction\n\n")
	for _, cmd := range reproductionCommands {
		b.WriteString("```bash\n" + cmd + "\n```\n\n")
	}

	for _, bench := range benchmarks {
		recs := byBenchmark[bench]
		version := recs[0].BenchmarkVersion
		fmt.Fprintf(&b, "## Benchmark: %s (version %s)\n\n", bench, version)

		// OFFICIAL BENCHMARK METRIC: verbatim official fields, per instance.
		b.WriteString("### OFFICIAL BENCHMARK METRIC\n\n")
		b.WriteString("Source: the official evaluator result object, unmodified.\n\n")
		b.WriteString("| instance_id | official fields (verbatim) |\n|---|---|\n")
		for _, r := range recs {
			fmt.Fprintf(&b, "| `%s` | `%s` |\n", r.InstanceID, compactJSON(r.Official))
		}
		b.WriteString("\n")

		// SPLICE SUPPLEMENTAL TELEMETRY: per-instance rows, benchmark-local.
		b.WriteString("### SPLICE SUPPLEMENTAL TELEMETRY\n\n")
		b.WriteString("Supplemental Splice run data. Not a benchmark metric.\n\n")
		b.WriteString("| instance_id | input_tokens | output_tokens | cached_tokens | reasoning_tokens | model_calls | tool_calls | file_reads | searches | repairs | latency_ms | cost_usd | cost_provenance |\n")
		b.WriteString("|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
		for _, r := range recs {
			t := r.SpliceTelemetry
			if t == nil {
				fmt.Fprintf(&b, "| `%s` | - | - | - | - | - | - | - | - | - | - | - | - |\n", r.InstanceID)
				continue
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
				r.InstanceID,
				pn(t.InputTokens), pn(t.OutputTokens), pn(t.CachedTokens), pn(t.ReasoningTokens),
				pn(t.ModelCalls), pn(t.ToolCalls), pn(t.FileReads), pn(t.Searches), pn(t.Repairs),
				pn(t.LatencyMS), pf(t.CostUSD), t.CostProvenance)
		}
		b.WriteString("\n")
	}

	// Cross-benchmark evidence matrix: qualitative only.
	b.WriteString("## Cross-benchmark evidence matrix\n\n")
	b.WriteString("Qualitative only. Cells are `checks`, `cross`, or `na` and never\n")
	b.WriteString("numbers. Numeric comparison across benchmarks is forbidden; see\n")
	b.WriteString("benchmarks/report/guard.go.\n\n")
	b.WriteString("| benchmark | swebench_pro_os | terminal_bench | agentbench_style |\n")
	b.WriteString("|---|---|---|---|\n")
	for _, bench := range benchmarks {
		row := make([]string, 0, 3)
		for _, other := range []string{"swebench_pro_os", "terminal_bench", "agentbench_style"} {
			switch {
			case bench == other:
				row = append(row, "checks")
			case bench == "swebench_pro_os" || other == "swebench_pro_os":
				// overlap with the benchmark this repo runs today
				row = append(row, "cross")
			default:
				row = append(row, "na")
			}
		}
		fmt.Fprintf(&b, "| %s | %s |\n", bench, strings.Join(row, " | "))
	}
	b.WriteString("\n")

	b.WriteString("## Guard\n\n")
	b.WriteString("Cross-benchmark numeric aggregation is refused by\n")
	b.WriteString("`report.Aggregate` (benchmarks/report/guard.go). Any overall score\n")
	b.WriteString("or cross-benchmark token average is a bug, not a feature.\n")
	return b.String(), nil
}

// WriteMarkdown renders and writes STANDARDIZED_EVAL_REPORT.md to path.
func WriteMarkdown(path string, records []*Record, reproductionCommands []string) error {
	md, err := GenerateMarkdown(records, reproductionCommands)
	if err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(md), 0o644); err != nil {
		return fmt.Errorf("report.WriteMarkdown: write %s: %w", path, err)
	}
	return nil
}

func pn(p *int64) string {
	if p == nil {
		return "-"
	}
	return fmt.Sprint(*p)
}

func pf(p *float64) string {
	if p == nil {
		return "-"
	}
	return fmt.Sprintf("%.4f", *p)
}

func compactJSON(m map[string]any) string {
	data, err := json.Marshal(m)
	if err != nil {
		return "{}"
	}
	return escapePipe(string(data))
}

// escapePipe keeps verbatim JSON inside a Markdown table cell intact.
func escapePipe(s string) string {
	return strings.ReplaceAll(s, "|", "\\|")
}
